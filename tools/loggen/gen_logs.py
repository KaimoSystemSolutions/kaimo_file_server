def gen_resx(rows):
    out = [RESX_HEADER]
    for name, eid, msg in rows:
        out.append(f'  <data name="{name}" xml:space="preserve">')
        out.append(f'    <value>{html.escape(msg, quote=False)}</value>')
        out.append('  </data>')
    out.append('</root>')
    return "\n".join(out) + "\n"

def gen_designer(rows):
    out = []
    out.append("//------------------------------------------------------------------------------")
    out.append("// <auto-generated>")
    out.append("//     Generated from LogMessages.resx. Do not edit by hand; regenerate instead.")
    out.append("// </auto-generated>")
    out.append("//------------------------------------------------------------------------------")
    out.append("")
    out.append("namespace Kaimo_File_Server.Core.Logging {")
    out.append("    using System;")
    out.append("")
    out.append("    /// <summary>")
    out.append("    ///   English (invariant) log message templates. Companion to <see cref=\"LogEvents\"/>.")
    out.append("    /// </summary>")
    out.append("    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"System.Resources.Tools.StronglyTypedResourceBuilder\", \"18.0.0.0\")]")
    out.append("    [global::System.Diagnostics.DebuggerNonUserCodeAttribute()]")
    out.append("    [global::System.Runtime.CompilerServices.CompilerGeneratedAttribute()]")
    out.append("    public class LogMessages {")
    out.append("")
    out.append("        private static global::System.Resources.ResourceManager resourceMan;")
    out.append("")
    out.append("        private static global::System.Globalization.CultureInfo resourceCulture;")
    out.append("")
    out.append("        [global::System.Diagnostics.CodeAnalysis.SuppressMessageAttribute(\"Microsoft.Performance\", \"CA1811:AvoidUncalledPrivateCode\")]")
    out.append("        internal LogMessages() {")
    out.append("        }")
    out.append("")
    out.append("        [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]")
    out.append("        public static global::System.Resources.ResourceManager ResourceManager {")
    out.append("            get {")
    out.append("                if (object.ReferenceEquals(resourceMan, null)) {")
    out.append("                    global::System.Resources.ResourceManager temp = new global::System.Resources.ResourceManager(\"Kaimo_File_Server.Core.Logging.LogMessages\", typeof(LogMessages).Assembly);")
    out.append("                    resourceMan = temp;")
    out.append("                }")
    out.append("                return resourceMan;")
    out.append("            }")
    out.append("        }")
    out.append("")
    out.append("        [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]")
    out.append("        public static global::System.Globalization.CultureInfo Culture {")
    out.append("            get {")
    out.append("                return resourceCulture;")
    out.append("            }")
    out.append("            set {")
    out.append("                resourceCulture = value;")
    out.append("            }")
    out.append("        }")
    for name, eid, msg in rows:
        summary = html.escape(msg, quote=False)
        out.append("")
        out.append("        /// <summary>")
        out.append(f"        ///   Looks up a localized string similar to {summary}.")
        out.append("        /// </summary>")
        out.append(f"        public static string {name} {{")
        out.append("            get {")
        out.append(f"                return ResourceManager.GetString(\"{name}\", resourceCulture);")
        out.append("            }")
        out.append("        }")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"

def main():
    rows = load()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "LogEvents.cs"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(gen_events(rows))
    with open(os.path.join(OUT, "LogMessages.resx"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(gen_resx(rows))
    with open(os.path.join(OUT, "LogMessages.Designer.cs"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(gen_designer(rows))
    print(f"Generated {len(rows)} log messages -> {OUT}")

if __name__ == "__main__":
    main()
