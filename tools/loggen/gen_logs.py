#!/usr/bin/env python3
"""Generate LogEvents.cs, LogMessages.resx and LogMessages.Designer.cs from a TSV master.

TSV columns (tab separated), lines starting with '#' or blank are ignored:
    Name <TAB> EventId <TAB> Message

The EventId's thousands-digit selects the owning project region.
Message uses named structured-logging placeholders, e.g. "Share sync failed for {Share}".
"""
import sys, os, html, re

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, "logmessages.tsv")
# tools/loggen -> repo root -> src/.../Core/Logging
OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "src", "Kaimo_File_Server.Core", "Logging"))

RANGES = [
    (1000, 1999, "Core"),
    (2000, 2999, "Infrastructure"),
    (3000, 3999, "Search"),
    (4000, 4999, "Smb"),
    (5000, 5999, "Web"),
    (6000, 6999, "Host"),
]

def region_for(eid):
    for lo, hi, name in RANGES:
        if lo <= eid <= hi:
            return name
    raise SystemExit(f"EventId {eid} out of defined ranges")

def load():
    rows = []
    seen_name, seen_id = {}, {}
    with open(TSV, encoding="utf-8") as f:
        for ln, raw in enumerate(f, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                raise SystemExit(f"{TSV}:{ln}: expected 3 tab-separated columns, got {len(parts)}: {line!r}")
            name, eid, msg = parts[0].strip(), parts[1].strip(), parts[2]
            if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name):
                raise SystemExit(f"{TSV}:{ln}: invalid name {name!r}")
            eid = int(eid)
            if name in seen_name:
                raise SystemExit(f"{TSV}:{ln}: duplicate name {name!r} (first at line {seen_name[name]})")
            if eid in seen_id:
                raise SystemExit(f"{TSV}:{ln}: duplicate id {eid} (first at line {seen_id[eid]})")
            seen_name[name] = ln
            seen_id[eid] = ln
            rows.append((name, eid, msg))
    return rows

def gen_events(rows):
    by_region = {}
    for name, eid, msg in rows:
        by_region.setdefault(region_for(eid), []).append((eid, name))
    out = []
    out.append("// <auto-generated> — generated from logmessages master. Do not edit by hand;")
    out.append("// add entries to the log-message source and regenerate.")
    out.append("using Microsoft.Extensions.Logging;")
    out.append("")
    out.append("namespace Kaimo_File_Server.Core.Logging;")
    out.append("")
    out.append("/// <summary>")
    out.append("/// Central catalog of <see cref=\"EventId\"/> codes = the \"where did this come from\" map for logs.")
    out.append("/// Numeric ranges are assigned per project so a bare <c>[nnnn]</c> in a log line points straight")
    out.append("/// at the owning subsystem:")
    out.append("/// <list type=\"bullet\">")
    for lo, hi, name in RANGES:
        out.append(f"/// <item><c>{lo}-{hi}</c> — {name}</item>")
    out.append("/// </list>")
    out.append("/// Each event name matches a key in <see cref=\"LogMessages\"/> holding the English template.")
    out.append("/// </summary>")
    out.append("public static class LogEvents")
    out.append("{")
    first = True
    for lo, hi, region in RANGES:
        items = sorted(by_region.get(region, []))
        if not items:
            continue
        if not first:
            out.append("")
        first = False
        out.append(f"    #region {region} ({lo}-{hi})")
        out.append("")
        for eid, name in items:
            out.append(f"    public static readonly EventId {name} = new({eid}, nameof({name}));")
        out.append("")
        out.append("    #endregion")
    out.append("}")
    return "\n".join(out) + "\n"

